const assert = require('node:assert/strict');
const fs = require('node:fs'); const ts = require('typescript'); const Module = require('node:module');
const file = require('node:path').resolve('lib/characters.ts');
assert.ok(fs.existsSync(file), 'Character model has not been implemented');
const m = new Module(file, module); m.paths = module.paths;
m._compile(ts.transpileModule(fs.readFileSync(file,'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,file);
const { modifier, proficiency, checkBonus, createCharacter, normalizeCharacter, applyDamage } = m.exports;
for(const [level, bonus] of [[1,2],[4,2],[5,3],[9,4],[13,5],[17,6],[20,6]]) assert.equal(proficiency(level),bonus);
assert.equal(modifier(9),-1); assert.equal(modifier(15),2); assert.equal(checkBonus(15,5,2,1),9);
const c=createCharacter('Aria'); assert.equal(c.name,'Aria'); assert.equal(c.level,1);
const n=normalizeCharacter({...c,level:99,hpMax:10,hp:22,tempHp:-3,slots:[{max:2,current:8}]});
assert.equal(n.level,20); assert.equal(n.hp,10); assert.equal(n.tempHp,0); assert.equal(n.slots[0].current,2);
assert.equal(normalizeCharacter({...c,hpMax:NaN,hp:Infinity}).hpMax,1);
assert.deepEqual(applyDamage({...c,hpMax:20,hp:15,tempHp:5},8),{hp:12,tempHp:0});
assert.deepEqual(applyDamage({...c,hpMax:20,hp:15,tempHp:5},2),{hp:15,tempHp:3});
assert.notEqual(createCharacter('B').id,c.id);
assert.equal(m.exports.commitNumber('10.5',1,30),10);
assert.equal(m.exports.commitName('   '),'Personaggio senza nome');
assert.equal(m.exports.commitName('  Aria  '),'Aria');
console.log('Character model: proficiency, modifiers, mastery, bounds, temporary HP and IDs passed');
